import json
import subprocess
from unittest.mock import Mock

import pytest

from codex_telegram_bridge.desktop_booking import BoardError, DesktopBooking


OWNER = "00000000-0000-4000-8000-000000000003 /telegram-relay"
CANONICAL = "codex:00000003/telegram-relay"
GENERATED = "Generated by `board`. Do not edit; run `board help`.\n"


def result(data=None, code=0):
    return subprocess.CompletedProcess([], code, json.dumps({"ok": code == 0, "code": code, "data": data or {}}), "")


def held(owner=CANONICAL):
    return {"leases": [{"resource": "desktop", "owner": owner, "state": "held"}]}


@pytest.fixture
def booking(tmp_path, monkeypatch):
    (tmp_path / "desktop-control.md").write_text(GENERATED)
    booking = DesktopBooking(OWNER, tmp_path)
    booking.command = Mock()
    monkeypatch.setattr(subprocess, "run", booking.command)
    return booking


def test_generated_view_claim_uses_migrated_owner_and_never_edits_markdown(booking):
    booking.command.side_effect = [result({"leases": []}), result(), result(held())]
    assert booking.try_claim()
    assert booking.board.read_text() == GENERATED
    commands = booking.command.call_args_list
    assert commands[1].args[0][1:3] == ["claim", "desktop"]
    assert all(c.kwargs["env"]["BOARD_OWNER"] == CANONICAL for c in commands)
    assert "--take-dead" not in commands[1].args[0]


def test_busy_or_queue_priority_refusal_queues_without_editing_view(booking):
    booking.command.side_effect = [result(held("script:other")), result(code=2), result()]
    assert not booking.try_claim()
    assert booking.command.call_args.args[0][1:3] == ["queue", "desktop"]
    assert booking.board.read_text() == GENERATED


def test_old_own_lease_requires_review_instead_of_reusing_it(booking):
    booking.command.return_value = result(held())
    with pytest.raises(BoardError, match="earlier bridge booking"):
        booking.try_claim()
    booking.command.assert_called_once()


async def test_failure_releases_only_the_lease_claimed_by_this_instance(booking):
    booking.command.side_effect = [result({"leases": []}), result(), result(held()),
                                   result(held()), result(held()), result()]
    with pytest.raises(ValueError):
        async with booking.hold():
            raise ValueError("UI failure")
    assert booking.command.call_args.args[0][1:3] == ["release", "desktop"]
    assert not booking._cli_claimed
    assert booking.board.read_text() == GENERATED


def test_lost_ownership_blocks_ui_and_cannot_release_another_owner(booking):
    booking._cli_claimed = True
    booking.command.return_value = result(held("script:other"))
    with pytest.raises(BoardError, match="ownership changed"):
        booking.verify()
    with pytest.raises(BoardError, match="ownership changed"):
        booking.release()
    assert all(c.args[0][1] == "status" for c in booking.command.call_args_list)


def test_cancel_removes_only_this_owner_queue_entry_via_cli(booking):
    booking.command.return_value = result()
    booking.cancel_reservation()
    assert booking.command.call_args.args[0][1:] == ["queue", "desktop", "--leave", "--json"]
    assert booking.command.call_args.kwargs["env"]["BOARD_OWNER"] == CANONICAL
    assert booking.board.read_text() == GENERATED


@pytest.mark.parametrize("response", [subprocess.CompletedProcess([], 1, "", "failure"),
    subprocess.CompletedProcess([], 0, "{}", ""), result({"leases": "unknown"})])
def test_unavailable_or_ambiguous_cli_fails_closed(booking, response):
    booking.command.return_value = response
    with pytest.raises(BoardError):
        booking.try_claim()
    assert booking.board.read_text() == GENERATED


def test_migration_between_detection_and_lock_never_edits_generated_view(booking):
    with pytest.raises(BoardError, match="migrated"):
        with booking.edit():
            pytest.fail("Generated view must not be edited")
    assert booking._using_cli
    assert booking.board.read_text() == GENERATED
