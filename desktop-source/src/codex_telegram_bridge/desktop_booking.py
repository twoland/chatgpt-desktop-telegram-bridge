"""Cooperative desktop leases through an installed CLI or explicit legacy board."""
from __future__ import annotations

import asyncio
import fcntl
import json
import os
import re
import subprocess
from contextlib import asynccontextmanager, contextmanager
from datetime import datetime, timedelta, timezone
from pathlib import Path
from tempfile import NamedTemporaryFile


class BoardError(RuntimeError):
    pass


LEGACY_BOARD = """# Desktop Control
## Current use
Status: FREE
Owner: none
Task: none
Apps: none
Started: none
Expected finish: none
Updated: never
## Reservations
| Requested at | Owner | Slot | Task | Apps | Estimate |
| --- | --- | --- | --- | --- | --- |
## Messages
- All desktop users must claim before interaction and release when finished.
"""


def initialize_legacy_board(home=None):
    """Explicit operator setup only; never replace an existing coordination board."""
    home = Path(home) if home is not None else Path.home()
    if (home / ".local/bin/board").exists():
        raise BoardError("Use the installed board CLI's setup; do not replace its generated view")
    with (home / ".desktop-control.edit.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        path = home / "desktop-control.md"
        with path.open("x") as handle:
            os.chmod(path, 0o600)
            handle.write(LEGACY_BOARD)
    return path


class DesktopBooking:
    def __init__(self, owner: str, home: Path | None = None):
        home = home or Path.home()
        self.owner = owner
        self.board = home / "desktop-control.md"
        self.lock = home / ".desktop-control.edit.lock"
        self.board_command = home / ".local/bin/board"
        self._using_cli = False
        self._cli_claimed = False

    def uses_cli(self):
        # The installed board is a generated view of SQLite, not a writable
        # Markdown protocol. Once detected, never fall back to editing its view.
        try:
            text = self.board.read_text()
        except FileNotFoundError as exc:
            raise BoardError("Desktop board is missing. See README setup before using the desktop") from exc
        if text.startswith("Generated by `board`."):
            self._using_cli = True
        return self._using_cli

    def cli_owner(self):
        match = re.fullmatch(r"([0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}) /([A-Za-z0-9._/-]+)", self.owner)
        if match:
            # Match the board's migration of the relay's legacy thread label.
            return f"codex:{match[1][-8:]}/{match[2]}"
        if re.fullmatch(r"(?:codex|claude|script|human):[A-Za-z0-9._-]+(?:/[A-Za-z0-9._-]+)*", self.owner):
            return self.owner
        raise BoardError("Cannot map relay identity to the installed board")

    def cli(self, *arguments, allow_refusal=False):
        environment = {**os.environ, "BOARD_OWNER": self.cli_owner()}
        try:
            result = subprocess.run(
                [str(self.board_command), *arguments, "--json"],
                env=environment, capture_output=True, text=True, timeout=5,
            )
            response = json.loads(result.stdout)
        except (OSError, subprocess.TimeoutExpired, ValueError) as exc:
            raise BoardError("Installed board unavailable; desktop interaction stopped") from exc
        if (not isinstance(response, dict) or response.get("code") != result.returncode
                or result.returncode not in ({0, 2} if allow_refusal else {0})):
            raise BoardError("Installed board refused the operation; check board status")
        if result.returncode == 0 and response.get("ok") is not True:
            raise BoardError("Installed board did not confirm the operation")
        return response

    def cli_leases(self):
        data = self.cli("status", "desktop").get("data", {})
        leases = data.get("leases")
        if not isinstance(leases, list) or data.get("maintenance_errors") or data.get("unreadable"):
            raise BoardError("Cannot safely verify installed desktop board")
        return leases

    def try_claim_cli(self):
        if any(lease.get("owner") == self.cli_owner() for lease in self.cli_leases()):
            raise BoardError("An earlier bridge booking is still BUSY; review before recovery")
        response = self.cli("claim", "desktop", "--task", "Deliver Telegram input",
                            "--apps", "ChatGPT", "--est", "60s", "--lease", "2m", allow_refusal=True)
        if response["code"] == 2:
            self.cli("queue", "desktop", "--task", "Deliver Telegram input")
            return False
        self._cli_claimed = True
        self.verify()
        return True

    @contextmanager
    def edit(self):
        with self.lock.open("a") as handle:
            fcntl.flock(handle, fcntl.LOCK_EX)
            text = self.board.read_text()
            if text.startswith("Generated by `board`."):
                self._using_cli = True
                raise BoardError("Desktop board migrated; retry through the installed board CLI")
            yield text

    @staticmethod
    def field(text, name):
        values = re.findall(rf"^{re.escape(name)}: (.*)$", text, re.M)
        if len(values) != 1:
            raise BoardError(f"Ambiguous or missing board field: {name}")
        return values[0]

    @staticmethod
    def reservations(text):
        if text.count("## Reservations") != 1 or text.count("## Messages") != 1:
            raise BoardError("Cannot safely read desktop reservations")
        section = text.split("## Reservations", 1)[1].split("## Messages", 1)[0]
        rows = []
        for line in section.splitlines():
            if not line.startswith("|"):
                continue
            cells = [cell.strip() for cell in line.strip("|").split("|")]
            if cells[0] == "Requested at" or all(set(c) <= {"-", ":", " "} for c in cells):
                continue
            if len(cells) != 6:
                raise BoardError("Unrecognized desktop reservation")
            rows.append((line, cells))
        return rows

    def write(self, text, message, **fields):
        now = datetime.now(timezone.utc).isoformat()
        for name, value in {**fields, "Updated": now}.items():
            self.field(text, name)
            text = re.sub(rf"^{re.escape(name)}: .*$", lambda _: f"{name}: {value}", text, flags=re.M)
        text = text.rstrip() + f"\n\n- {now} — {self.owner}: {message}\n"
        with NamedTemporaryFile("w", dir=self.board.parent, delete=False) as handle:
            handle.write(text)
            temporary = Path(handle.name)
        temporary.chmod(self.board.stat().st_mode & 0o777)
        temporary.replace(self.board)

    def try_claim(self):
        if self.uses_cli():
            return self.try_claim_cli()
        with self.edit() as text:
            status = self.field(text, "Status")
            owner = self.field(text, "Owner")
            if status not in {"BUSY", "FREE"}:
                raise BoardError("Unknown desktop status; manual review needed")
            if status == "FREE" and owner not in {"none", "—", ""}:
                raise BoardError("FREE board still has an owner; manual review needed")
            # An old claim, even with this same owner, must not be treated as expired.
            if status == "BUSY" and owner == self.owner:
                raise BoardError("An earlier bridge booking is still BUSY; review before recovery")
            rows = self.reservations(text)
            now = datetime.now(timezone.utc)
            next_rows = [cells for _, cells in rows if cells[2] == "NEXT"]
            eligible = status == "FREE" and (not next_rows or next_rows[0][1] == self.owner)
            for _, cells in rows:
                if cells[2] == "NEXT":
                    continue
                try:
                    start, end = [datetime.fromisoformat(v.strip()) for v in cells[2].split("/")]
                    if start.tzinfo is None or end.tzinfo is None or end <= start:
                        raise ValueError
                except ValueError:
                    eligible = False  # Unrecognized formats require coordination.
                    continue
                if start <= now + timedelta(seconds=90):
                    eligible = False  # Includes missed windows: never silently take over.
            if not eligible:
                if not any(cells[1] == self.owner for _, cells in rows):
                    row = f"| {now.isoformat()} | {self.owner} | NEXT | Deliver Telegram input | ChatGPT | 60 seconds |\n\n"
                    text = text.replace("## Messages", row + "## Messages", 1)
                    self.write(text, "Reserved NEXT for Telegram delivery; waiting for desktop to be free.")
                return False
            for line, cells in rows:
                if cells[1] == self.owner:
                    text = text.replace(line + "\n", "", 1)
            self.write(text, "CLAIM — Telegram delivery, ChatGPT, estimate 60 seconds.",
                       Status="BUSY", Owner=self.owner, Task="Telegram delivery",
                       Apps="ChatGPT", Started=now.isoformat(),
                       **{"Expected finish": (now + timedelta(seconds=60)).isoformat()})
            return True

    def verify(self):
        if self.uses_cli():
            leases = self.cli_leases()
            if (not self._cli_claimed or len(leases) != 1
                    or leases[0].get("resource") != "desktop"
                    or leases[0].get("owner") != self.cli_owner()
                    or leases[0].get("state") != "held"):
                raise BoardError("Desktop ownership changed; stopping UI interaction")
            return
        with self.edit() as text:
            if self.field(text, "Status") != "BUSY" or self.field(text, "Owner") != self.owner:
                raise BoardError("Desktop ownership changed; stopping UI interaction")
            self.reservations(text)

    def release(self):
        if self.uses_cli():
            self.verify()
            self.cli("release", "desktop", "--note", "Telegram UI operation finished; desktop FREE.")
            self._cli_claimed = False
            return
        with self.edit() as text:
            if self.field(text, "Status") != "BUSY" or self.field(text, "Owner") != self.owner:
                raise BoardError("Cannot release a desktop owned by someone else")
            self.write(text, "RELEASE — Telegram UI operation finished; desktop FREE.",
                       Status="FREE", Owner="none", Task="none", Apps="none", Started="none",
                       **{"Expected finish": "none"})

    def cancel_reservation(self):
        if self.uses_cli():
            self.cli("queue", "desktop", "--leave")
            return
        with self.edit() as text:
            changed = False
            for line, cells in self.reservations(text):
                if cells[1] == self.owner:
                    text = text.replace(line + "\n", "", 1)
                    changed = True
            if changed:
                self.write(text, "Cancelled Telegram delivery reservation.")

    @asynccontextmanager
    async def hold(self):
        claimed = False
        try:
            while not self.try_claim():
                await asyncio.sleep(2)
            claimed = True
            self.verify()
            async with asyncio.timeout(55):
                yield
        finally:
            if claimed:
                self.release()
            else:
                self.cancel_reservation()
